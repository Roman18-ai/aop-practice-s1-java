
package leetcode;

public class FloatingPointDiscussion {

    public static void main(String[] args) {

        // 1. Чому існують окремі цілі та дробові типи?
        System.out.println("1. Цілі типи зберігають цілі числа, " +
                "а дробові — числа з десятковою частиною. " +
                "Вони відрізняються способом зберігання та точністю.");

        // 2. Що означає floating point?
        System.out.println("2. Floating point — це спосіб представлення " +
                "чисел, коли десяткова крапка може умовно переміщуватися. " +
                "Число зберігається у вигляді значущої частини та степеня.");

        // 3. Скільки цифр після коми може зберігати комп'ютер?
        System.out.println("3. Тип float має приблизно 7 значущих десяткових цифр, " +
                "а double — приблизно 15-16. Це не фіксована кількість цифр після коми.");

        // 4. Чому 0.1 + 0.2 не дорівнює точно 0.3?
        System.out.println("4. Деякі десяткові дроби неможливо точно представити " +
                "у двійковій системі, тому виникає невелика похибка.");

        // 5. Чому не варто зберігати гроші в double?
        System.out.println("5. Тип double може давати похибки під час обчислень. " +
                "Для грошей краще використовувати BigDecimal або цілі копійки.");

        // 6. Чи може число бути нерівним самому собі?
        System.out.println("6. Так. Спеціальне значення NaN (Not a Number) " +
                "не дорівнює навіть самому собі.");

        System.out.println();
        System.out.println("Перевірка: 0.1 + 0.2 = " + (0.1 + 0.2));
        System.out.println("Перевірка NaN: " +
                (Double.NaN == Double.NaN));
    }
}
